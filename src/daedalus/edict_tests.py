"""
Edicts with tests attached (from the first dream, docs/dreams/2026-10-15.md, pick 38).

An edict's acceptance criteria become a test skeleton: one skipped, named test per criterion in
`tests/edicts/test_edict_NNNN.py`. Daedalus fills in the bodies as it builds; "is edict NNNN built?"
becomes a test run, and `daedalus doctor` hints at criteria whose test is still a skeleton.

- A criterion is a top-level bullet of the edict's `## Acceptance criteria` section (its sub-bullets
  belong to it).
- Each gets a stable ID: an explicit `[AC-name]` at the start of the bullet, or else a slug of its first
  words, so editing one criterion doesn't renumber the others.
- Writing the skeleton never overwrites a test that exists: only missing criteria are added, so it can be
  re-run after an amendment.
- A skeleton test is skipped with the reason `criterion not yet tested`. Replacing the skip with a real
  test is what marks the criterion tested.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

SKELETON_REASON = "criterion not yet tested"
EXPLICIT = re.compile(r"^\[(AC-[A-Za-z0-9_-]+)\]\s*")
STOP = {"a", "an", "the", "and", "or", "of", "to", "in", "on", "is", "are", "it", "its", "for", "with", "that", "by"}


@dataclass
class Criterion:
    id: str
    text: str


def _slug(text: str, words: int = 6) -> str:
    plain = re.sub(r"`|\*\*|\*", "", text).lower()
    tokens = [t for t in re.findall(r"[a-z0-9]+", plain) if t not in STOP]
    return "_".join(tokens[:words]) or "criterion"


def criteria(section: str) -> list[Criterion]:
    """The top-level bullets of an Acceptance criteria section, each with a stable ID."""
    items: list[list[str]] = []
    for line in section.splitlines():
        if re.match(r"^- ", line):
            items.append([line[2:].strip()])
        elif items and (line.startswith("  ") or not line.strip()):
            if line.strip():
                items[-1].append(line.strip())
    out: list[Criterion] = []
    seen: dict[str, int] = {}
    for parts in items:
        text = " ".join(parts)
        m = EXPLICIT.match(text)
        if m:
            cid, text = m.group(1).lower().replace("-", "_"), text[m.end():]
        else:
            cid = _slug(text)
        seen[cid] = seen.get(cid, 0) + 1
        if seen[cid] > 1:
            cid = f"{cid}_{seen[cid]}"
        out.append(Criterion(cid, text))
    return out


def edict_criteria(repo: Path, number: str) -> list[Criterion]:
    from .edicts import load_edict

    return criteria(load_edict(repo, number).sections.get("Acceptance criteria", ""))


def skeleton_path(repo: Path, number: str) -> Path:
    return Path(repo) / "tests" / "edicts" / f"test_edict_{str(number).zfill(4)}.py"


def criterion_test_name(number: str, cid: str) -> str:
    return f"test_{str(number).zfill(4)}_{cid}"


def _docstring(text: str) -> str:
    wrapped, line = [], ""
    for word in text.replace('"""', "'''").split():
        if len(line) + len(word) + 1 > 92:
            wrapped.append(line)
            line = word
        else:
            line = f"{line} {word}".strip()
    wrapped.append(line)
    return "\n    ".join(wrapped)


def skeleton(number: str, crit: Criterion) -> str:
    return (f"\n\n@pytest.mark.skip(reason={SKELETON_REASON!r})\n"
            f"def {criterion_test_name(number, crit.id)}():\n"
            f'    """{_docstring(crit.text)}"""\n')


def write_skeleton(repo: Path, number: str) -> tuple[Path, list[str]]:
    """Add a skipped test for every criterion that has none. Returns (path, the test names added)."""
    from .edicts import load_edict

    edict = load_edict(repo, number)
    crits = criteria(edict.sections.get("Acceptance criteria", ""))
    path = skeleton_path(repo, edict.number)
    existing = path.read_text(encoding="utf-8") if path.exists() else (
        f'"""Edict {edict.number} ({edict.title}): one test per acceptance criterion.\n\n'
        f"Generated by `daedalus edict tests {edict.number} --write`. Replace each skip with a real test;\n"
        f're-running the command adds tests only for criteria that have none."""\n\nimport pytest\n')
    added = []
    for c in crits:
        name = criterion_test_name(edict.number, c.id)
        if re.search(rf"^def {re.escape(name)}\(", existing, re.M):
            continue
        existing += skeleton(edict.number, c)
        added.append(name)
    if added or not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(existing, encoding="utf-8")
    return path, added


def status(repo: Path, number: str) -> dict:
    """{criterion id: "tested" | "skeleton" | "missing"} for one edict."""
    path = skeleton_path(repo, number)
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    out = {}
    for c in edict_criteria(repo, number):
        name = criterion_test_name(number, c.id)
        m = re.search(rf"((?:^@.*\n)*)^def {re.escape(name)}\(", text, re.M)
        if not m:
            out[c.id] = "missing"
        elif SKELETON_REASON in m.group(1):
            out[c.id] = "skeleton"
        else:
            out[c.id] = "tested"
    return out
