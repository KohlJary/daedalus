"""
A state-of-the-project page (from the first dream, docs/dreams/2026-10-15.md, pick 33).

One self-contained HTML file a newcomer can read before installing anything: the active phase and its
tasks, every phase, the edicts and their status, what's waiting on the owner, the roadmap's intake by
origin, and the latest session note. It is built from the same library functions the CLI and TUI use,
and contains nothing from `.daedalus/` that isn't already committed or meant to be shared: no reflection
data, no models, no dreams, no board posts, no config.

`daedalus page [--out PATH]` writes it (default `.daedalus/page/index.html`, local). Sharing it,
committing it or publishing it is the owner's choice.
"""

from __future__ import annotations

import html
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

CSS = """
:root { --bg: #fbfaf7; --fg: #1d1d1b; --muted: #6b6a66; --line: #e3e1da; --accent: #8a5a00; --ok: #2f6f3e; --warn: #9a4d00; }
@media (prefers-color-scheme: dark) { :root { --bg: #161614; --fg: #ecebe6; --muted: #a09e97; --line: #2e2d29; --accent: #e0a64a; --ok: #7cc48b; --warn: #f0a35b; } }
* { box-sizing: border-box; }
body { margin: 0; background: var(--bg); color: var(--fg); font: 15px/1.55 system-ui, -apple-system, Segoe UI, sans-serif; }
main { max-width: 860px; margin: 0 auto; padding: 32px 16px 64px; }
h1 { font-size: 28px; margin: 0 0 4px; } h2 { font-size: 18px; margin: 36px 0 10px; border-bottom: 1px solid var(--line); padding-bottom: 6px; }
.sub { color: var(--muted); margin: 0 0 24px; } .tag { font: 12px ui-monospace, monospace; padding: 1px 6px; border: 1px solid var(--line); border-radius: 4px; color: var(--muted); }
ul { padding-left: 20px; } li { margin: 4px 0; } code { font: 13px ui-monospace, monospace; }
.done { color: var(--ok); } .prog { color: var(--accent); } .warn { color: var(--warn); }
.note { white-space: pre-wrap; background: color-mix(in srgb, var(--line) 35%, transparent); padding: 12px 14px; border-radius: 6px; }
table { border-collapse: collapse; width: 100%; } td, th { text-align: left; padding: 4px 8px; border-bottom: 1px solid var(--line); vertical-align: top; }
footer { margin-top: 48px; color: var(--muted); font-size: 13px; }
"""

ICON = {"done": "✓", "in_progress": "▸", "pending": "○", "planned": "○"}


def _e(text) -> str:
    return html.escape(str(text or ""))


def _task_li(t: dict) -> str:
    cls = {"done": "done", "in_progress": "prog"}.get(t.get("status"), "")
    res = f" <span class='sub'>— {_e(t.get('resolution', ''))[:220]}</span>" if t.get("status") == "done" and t.get("resolution") else ""
    return f"<li class='{cls}'>{ICON.get(t.get('status'), '○')} <code>{_e(t.get('id'))}</code> {_e(t.get('title'))}{res}</li>"


def build(project_dir: Path, now: Optional[datetime] = None) -> str:
    from . import roadmap
    from .cli import gameplan as gp
    from .doctor import load_edicts

    project_dir = Path(project_dir)
    name = project_dir.resolve().name
    now = now or datetime.now(timezone.utc)
    parts = [f"<h1>{_e(name)}</h1>",
             "<p class='sub'>What this project is building, what's next, and what's been decided. "
             "Generated by <code>daedalus page</code> from the project's own records.</p>"]

    try:
        plan = gp.load_gameplan(project_dir)
    except gp.GameplanError:
        plan = {}
    active = plan.get("activePhase") or {}
    parts.append("<h2>Now</h2>")
    if active:
        tasks = active.get("tasks", [])
        done = sum(1 for t in tasks if t.get("status") == "done")
        parts.append(f"<p><b>{_e(active.get('title'))}</b> <span class='tag'>{_e(active.get('id'))}</span> "
                     f"<span class='sub'>{done} of {len(tasks)} tasks done</span></p>")
        if active.get("goal"):
            parts.append(f"<p>{_e(active['goal'])}</p>")
        open_tasks = [t for t in tasks if t.get("status") != "done"]
        parts.append("<ul>" + "".join(_task_li(t) for t in open_tasks) + "</ul>" if open_tasks
                     else "<p class='sub'>Every task in this phase is done.</p>")
    else:
        parts.append("<p class='sub'>No phase is active.</p>")

    phases = plan.get("phases", [])
    if phases:
        parts.append("<h2>The plan</h2><table><tr><th></th><th>Phase</th><th>Edict</th></tr>")
        for p in phases:
            mark = {"done": "<span class='done'>✓ done</span>", "in_progress": "<span class='prog'>▸ now</span>"}.get(
                p.get("status"), "○ planned")
            parts.append(f"<tr><td>{mark}</td><td>{_e(p.get('title'))}</td><td>{_e(p.get('edict', ''))}</td></tr>")
        parts.append("</table>")

    edicts = load_edicts(project_dir)
    if edicts:
        parts.append("<h2>Decisions (edicts)</h2><p class='sub'>Design decisions handed to the builder. "
                     "Accepted ones are approved to build; done ones are built.</p><ul>")
        for e in edicts:
            path = project_dir / "docs" / "edicts" / e["file"]
            first = path.read_text(encoding="utf-8").splitlines()[0] if path.exists() else e["file"]
            title = first.split(":", 1)[1].strip() if ":" in first else e["file"]
            status = e.get("status") or "?"
            cls = {"done": "done", "accepted": "prog", "proposed": "warn"}.get(status, "")
            parts.append(f"<li><code>{_e(e['number'])}</code> {_e(title)} <span class='{cls}'>({_e(status)})</span></li>")
        parts.append("</ul>")

    try:
        items = roadmap.load_index(project_dir).get("items", [])
    except roadmap.RoadmapError:
        items = []
    if items:
        by_origin: dict[str, list] = {}
        for i in items:
            by_origin.setdefault(roadmap.origin(i)["source"], []).append(i)
        parts.append("<h2>Intake (the roadmap)</h2><p class='sub'>Everything that's been asked for, by where it came "
                     "from. Phases pull items in.</p><table><tr><th>From</th><th>Waiting</th><th>Done</th></tr>")
        for src, its in sorted(by_origin.items()):
            parts.append(f"<tr><td>{_e(src)}</td><td>{sum(1 for i in its if i.get('status') != 'done')}</td>"
                         f"<td>{sum(1 for i in its if i.get('status') == 'done')}</td></tr>")
        parts.append("</table>")

    status_md = project_dir / "docs" / "status.md"
    if status_md.exists():
        text = status_md.read_text(encoding="utf-8")
        first_section = re.split(r"^## ", text, maxsplit=2, flags=re.M)
        if len(first_section) > 1:
            parts.append("<h2>Latest note</h2>")
            parts.append(f"<div class='note'>## {_e(first_section[1].strip())[:4000]}</div>")

    parts.append(f"<footer>Generated {now.strftime('%Y-%m-%d %H:%M UTC')} by Daedalus. "
                 "Built from the committed gameplan, edicts, roadmap and docs/status.md.</footer>")
    return ("<!doctype html><html lang='en'><head><meta charset='utf-8'>"
            "<meta name='viewport' content='width=device-width, initial-scale=1'>"
            f"<title>{_e(name)}: project state</title><style>{CSS}</style></head><body><main>"
            + "\n".join(parts) + "</main></body></html>\n")


def write(project_dir: Path, out: Optional[Path] = None) -> Path:
    out = Path(out) if out else Path(project_dir) / ".daedalus" / "page" / "index.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build(project_dir), encoding="utf-8")
    return out
